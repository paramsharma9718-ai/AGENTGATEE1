"""Workflow and Action Proposal Models for AGENTGATE Module 03.

Enforces strict separation between AI action proposals and trusted authorization:
- ActionProposal contains ONLY the requested operation, resource, recipient, and parameters.
- ActionProposal DOES NOT contain authorization fields (cannot self-authorize).
- ExecutionResult encapsulates the execution status and decision from the Gateway.
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator

from models.action_request import Operation, AuthorizationResponse, AuthorizationDecision, RiskLevel


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class ExecutionStatus(str, enum.Enum):
    SUCCESS = "SUCCESS"
    BLOCKED = "BLOCKED"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    FAILED = "FAILED"


class ActionProposal(BaseModel):
    """Structured proposal generated by an AI Agent or User.
    
    Security Guarantee:
    Does NOT contain authorization decisions. The agent only proposes what it wants
    to do; it cannot decide or approve its own action.
    """
    proposal_id: str = Field(..., description="Unique proposal identifier")
    user_id: str = Field(..., description="Requesting user identifier")
    operation: Operation = Field(..., description="Requested operation type")
    resource_id: str = Field(..., description="Target document/report identifier")
    recipient_id: Optional[str] = Field(None, description="Intended recipient identifier if applicable")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Operation-specific arguments")
    created_at: datetime = Field(default_factory=utc_now, description="Timestamp of proposal creation")

    @field_validator("proposal_id", "user_id", "resource_id")
    def non_empty_strings(cls, v, info):
        if not v or not isinstance(v, str) or not v.strip():
            raise ValueError(f"{info.field_name} must be a non-empty string")
        return v.strip()


class ExecutionResult(BaseModel):
    """The result of an operation that passed through the Centralized Execution Gateway."""
    proposal_id: str
    status: ExecutionStatus
    operation: Operation
    resource_id: str
    user_id: str
    recipient_id: Optional[str] = None
    authorization_response: Optional[AuthorizationResponse] = None
    output: Optional[Any] = None
    error_message: Optional[str] = None
    executed_at: datetime = Field(default_factory=utc_now)


class WorkflowStatus(str, enum.Enum):
    CREATED = "CREATED"
    RUNNING = "RUNNING"
    SUSPENDED = "SUSPENDED"
    COMPLETED = "COMPLETED"
    BLOCKED = "BLOCKED"
    FAILED = "FAILED"


class WorkflowStep(BaseModel):
    step_id: str
    proposal: ActionProposal
    status: ExecutionStatus = ExecutionStatus.PENDING_APPROVAL
    result: Optional[ExecutionResult] = None


class WorkflowState(BaseModel):
    workflow_id: str
    user_id: str
    status: WorkflowStatus = WorkflowStatus.CREATED
    steps: List[WorkflowStep] = Field(default_factory=list)
    current_step_index: int = 0
    created_at: datetime = Field(default_factory=utc_now)
    updated_at: datetime = Field(default_factory=utc_now)
